import Joi from 'joi';

export const createRegistrationFormSchema = Joi.object({
  form_no: Joi.string().trim(),
  formNo: Joi.string().trim(),
  guest_name: Joi.string().trim(),
  guest: Joi.string().trim(),
  first_name: Joi.string().allow('', null),
  firstName: Joi.string().allow('', null),
  last_name: Joi.string().allow('', null),
  lastName: Joi.string().allow('', null),
  email: Joi.string().email().allow('', null),
  phone: Joi.string().allow('', null),
  gender: Joi.string().allow('', null),
  address: Joi.string().allow('', null),
  city: Joi.string().allow('', null),
  country: Joi.string().allow('', null),
  arrival_date: Joi.date().iso().allow(null),
  arrivalDate: Joi.date().iso().allow(null),
  departure_date: Joi.date().iso().allow(null),
  departureDate: Joi.date().iso().allow(null),
  room_type: Joi.string().allow('', null),
  roomType: Joi.string().allow('', null),
  room_number: Joi.string().allow('', null),
  room: Joi.string().allow('', null),
  number_of_guests: Joi.number().min(1).default(1),
  numberOfGuests: Joi.number().min(1),
  id_type: Joi.string().allow('', null).default('National ID / Doc'),
  idType: Joi.string().allow('', null),
  id_number: Joi.string().allow('', null),
  idNumber: Joi.string().allow('', null),
  special_requests: Joi.string().allow('', null),
  specialRequests: Joi.string().allow('', null),
  status: Joi.string().default('Signed & Verified'),
  terms_accepted: Joi.boolean().default(true),
  stay_id: Joi.string().hex().length(24).allow(null),
  primary_guest_id: Joi.string().hex().length(24).allow(null),
});

