import Joi from "joi";

export const createEventSchema = Joi.object({
  event_ref: Joi.string().trim().optional(),
  name: Joi.string().trim().required().messages({
    "any.required": "Event name is required",
    "string.empty": "Event name cannot be empty",
  }),
  client_name: Joi.string().trim().allow("", null).optional(),
  client: Joi.string().trim().allow("", null).optional(),
  contact_email: Joi.string().trim().allow("", null).optional(),
  email: Joi.string().trim().allow("", null).optional(),
  contact_phone: Joi.string().trim().allow("", null).optional(),
  phone: Joi.string().trim().allow("", null).optional(),
  date: Joi.date().iso().allow("", null).optional(),
  start_date: Joi.date().iso().allow("", null).optional(),
  end_date: Joi.date().iso().allow("", null).optional(),
  start_time: Joi.string().trim().allow("", null).optional(),
  startTime: Joi.string().trim().allow("", null).optional(),
  end_time: Joi.string().trim().allow("", null).optional(),
  endTime: Joi.string().trim().allow("", null).optional(),
  expected_attendees: Joi.number().min(1).allow(null).optional(),
  guests: Joi.number().min(1).allow(null).optional(),
  event_type: Joi.string().trim().allow("", null).optional(),
  type: Joi.string().trim().allow("", null).optional(),
  venue: Joi.string().trim().allow("", null).optional(),
  catering: Joi.string().trim().allow("", null).optional(),
  status: Joi.string().trim().allow("", null).optional(),
  total_amount: Joi.number().min(0).allow(null).optional(),
  amount: Joi.number().min(0).allow(null).optional(),
  advance_amount: Joi.number().min(0).allow(null).optional(),
  advanceAmount: Joi.number().min(0).allow(null).optional(),
  balance_amount: Joi.number().min(0).allow(null).optional(),
  balanceAmount: Joi.number().min(0).allow(null).optional(),
  special_requests: Joi.string().trim().allow("", null).optional(),
  specialRequests: Joi.string().trim().allow("", null).optional(),
  notes: Joi.string().trim().allow("", null).optional(),
}).or("client_name", "client");

